#!/usr/bin/env bash
set -euo pipefail

# puddle-run — run a Puddle app without thinking about the plumbing.
#
# Usage:
#   ./puddle-run.sh setup              Configure server connection (one-time)
#   ./puddle-run.sh run [--key value]  Run the app
#   ./puddle-run.sh status             Show recent runs
#   ./puddle-run.sh help               Show this help
#
# Builder: fill in APP_NAME and WORKFLOW below, then commit this script
# to the app repo. The requester clones the repo and runs it.

# ── Builder config (fill these in) ──────────────────────────────────────

APP_NAME="Hertzner Start Stopper"
WORKFLOW="start-stop"

# ── Internals (requester does not touch these) ──────────────────────────

SERVER_URL=""
SERVER_TOKEN=""
CONFIG_DIR="${HOME}/.puddle"
CONFIG_FILE="${CONFIG_DIR}/config"

die()  { echo "Error: $*" >&2; exit 1; }
info() { echo "→ $*"; }

load_config() {
  if [[ -f "${CONFIG_FILE}" ]]; then
    # shellcheck source=/dev/null
    source "${CONFIG_FILE}"
  fi
  SERVER_URL="${PUDDLE_SERVER_URL:-${SERVER_URL}}"
  SERVER_TOKEN="${PUDDLE_TOKEN:-${SERVER_TOKEN}}"
}

require_config() {
  load_config
  [[ -n "${SERVER_URL}" ]] || die "Not configured. Run: $0 setup"
}

require_cli() {
  if ! command -v swamp >/dev/null 2>&1; then
    echo ""
    echo "This app requires a runtime to be installed."
    echo ""
    echo "Install it with:"
    echo "  curl -fsSL https://swamp-club.com/install | sh"
    echo ""
    echo "Then re-run this command."
    exit 1
  fi
}

# ── Commands ─────────────────────────────────────────────────────────────

cmd_setup() {
  require_cli
  mkdir -p "${CONFIG_DIR}"

  echo ""
  echo "Setting up ${APP_NAME}"
  echo "─────────────────────────────────"

  if [[ -f "${CONFIG_FILE}" ]]; then
    source "${CONFIG_FILE}"
    echo "Existing config found at ${CONFIG_FILE}"
    echo "  Server: ${PUDDLE_SERVER_URL:-<not set>}"
    echo ""
    read -rp "Reconfigure? [y/N] " yn
    [[ "${yn}" =~ ^[Yy] ]] || { info "Keeping existing config."; return 0; }
  fi

  local url token
  read -rp "Server URL (e.g. http://localhost:9090): " url
  [[ -n "${url}" ]] || die "Server URL is required."

  read -rp "Access token (leave blank for browser login): " token

  cat > "${CONFIG_FILE}" <<EOF
# puddle-run configuration — generated by setup
PUDDLE_SERVER_URL="${url}"
PUDDLE_TOKEN="${token}"
EOF
  chmod 600 "${CONFIG_FILE}"

  if [[ -z "${token}" ]]; then
    info "No token provided — logging in via browser..."
    swamp auth server-login --server "${url}"
  fi

  info "Config saved to ${CONFIG_FILE}"
  echo ""

  info "Testing connection..."
  if swamp workflow list --server "${url}" ${token:+--token "${token}"} --json >/dev/null 2>&1; then
    info "Connected successfully."
  else
    echo "Warning: could not connect to ${url}. Check the URL and try again."
  fi
}

cmd_run() {
  require_cli
  require_config

  local -a input_args=()
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --*)
        local key="${1#--}"
        shift
        [[ $# -gt 0 ]] || die "Missing value for --${key}"
        input_args+=("--input" "${key}=${1}")
        shift
        ;;
      *)
        die "Unknown argument: $1. Use --key value for inputs."
        ;;
    esac
  done

  info "Running ${APP_NAME}..."
  echo ""

  local raw_output
  raw_output=$(swamp workflow run "${WORKFLOW}" \
    --server "${SERVER_URL}" \
    ${SERVER_TOKEN:+--token "${SERVER_TOKEN}"} \
    --json \
    "${input_args[@]}" 2>/dev/null) || true

  local status
  status=$(echo "${raw_output}" | jq -r '.status // "unknown"' 2>/dev/null) || status="unknown"

  case "${status}" in
    succeeded)
      echo "Done."
      local report
      report=$(echo "${raw_output}" | jq -r '.reports[]? | select(.name == "@swamp/workflow-summary") | .json.steps[]? | select(.status == "succeeded") | "  ✓ \(.stepName)"' 2>/dev/null)
      [[ -n "${report}" ]] && echo "${report}"
      ;;
    failed)
      echo "Failed."
      local errors
      errors=$(echo "${raw_output}" | jq -r '.reports[]? | select(.name == "@swamp/workflow-summary") | .json.failures[]? | "  ✗ \(.stepName): \(.errorMessage | split("\n")[0])"' 2>/dev/null)
      [[ -n "${errors}" ]] && echo "${errors}"
      exit 1
      ;;
    *)
      echo "Status: ${status}"
      echo "${raw_output}" | jq -r '.reports[]? | select(.name == "@swamp/workflow-summary") | .markdown' 2>/dev/null || true
      ;;
  esac
}

cmd_status() {
  require_cli
  require_config

  info "Recent runs of ${APP_NAME}:"
  echo ""

  local raw_output
  raw_output=$(swamp workflow history list "${WORKFLOW}" \
    --server "${SERVER_URL}" \
    ${SERVER_TOKEN:+--token "${SERVER_TOKEN}"} \
    --json 2>/dev/null) || die "Could not fetch run history."

  echo "${raw_output}" | jq -r '
    .results[:5][] |
    "  \(.status | if . == "completed" then "✓" elif . == "failed" then "✗" else "…" end) \(.startedAt[:19] | gsub("T";" ")) — \(.status)"
  ' 2>/dev/null || echo "  No recent runs."
}

cmd_help() {
  echo ""
  echo "Usage: $0 <command> [options]"
  echo ""
  echo "Commands:"
  echo "  setup                Configure server connection (one-time)"
  echo "  run [--key value]    Run the app with the given inputs"
  echo "  status               Show recent runs"
  echo "  help                 Show this help"
  echo ""
  echo "Examples:"
  echo "  $0 setup"
  echo "  $0 run --action start"
  echo "  $0 status"
  echo ""
}

# ── Main ─────────────────────────────────────────────────────────────────

main() {
  local cmd="${1:-help}"
  shift || true

  case "${cmd}" in
    setup)   cmd_setup "$@" ;;
    run)     cmd_run "$@" ;;
    status)  cmd_status "$@" ;;
    help|-h|--help) cmd_help ;;
    *)       die "Unknown command: ${cmd}. Run '$0 help' for usage." ;;
  esac
}

main "$@"
